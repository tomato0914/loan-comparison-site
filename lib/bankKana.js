export function bankBaseName(bank) {
  return String(bank).replace(/（.*?）$/, "").replace(/銀行$/, "");
}

// 読みが登録されていない銀行は、銀行名そのものを返す
export function bankKana(bank) {
  const base = bankBaseName(bank);
  return BANK_KANA[base] ?? base;
}
